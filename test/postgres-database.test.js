const test = require('node:test');
const assert = require('node:assert/strict');

const { PostgresDatabase, prepareSql } = require('../src/postgres-database');

test('PostgreSQL SQL adapter translates positional and named parameters', () => {
  const positional = prepareSql('SELECT * FROM users WHERE id=? AND email=?', ['user-1', 'user@example.com']);
  assert.equal(positional.query, 'SELECT * FROM users WHERE id=$1 AND email=$2');
  assert.deepEqual(positional.values, ['user-1', 'user@example.com']);

  const named = prepareSql('INSERT INTO users (id,name,email) VALUES (@id,@name,@email)', {
    email: 'user@example.com',
    id: 'user-1',
    name: 'Test User',
  });
  assert.equal(named.query, 'INSERT INTO users (id,name,email) VALUES ($1,$2,$3)');
  assert.deepEqual(named.values, ['user-1', 'Test User', 'user@example.com']);
});

test('PostgreSQL SQL adapter preserves quoted question marks and handles SQLite dialect constructs', () => {
  const prepared = prepareSql(
    "SELECT * FROM departments WHERE name=? COLLATE NOCASE AND description='What?' ORDER BY name COLLATE NOCASE",
    ['Operations']
  );
  assert.equal(
    prepared.query,
    "SELECT * FROM departments WHERE LOWER(name) = LOWER($1) AND description='What?' ORDER BY LOWER(name)"
  );
  assert.deepEqual(prepared.values, ['Operations']);
});

test('PostgreSQL SQL adapter handles migrations and timestamp expressions', () => {
  const ignored = prepareSql("INSERT OR IGNORE INTO settings (key,value) VALUES ('mode','on')");
  assert.equal(ignored.query, "INSERT INTO settings (key,value) VALUES ('mode','on') ON CONFLICT DO NOTHING");

  const migration = prepareSql("CREATE TABLE calls (id INTEGER PRIMARY KEY AUTOINCREMENT, created_at TEXT DEFAULT CURRENT_TIMESTAMP, amount REAL)");
  assert.match(migration.query, /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(migration.query, /created_at TEXT DEFAULT CURRENT_TIMESTAMP::text/);
  assert.match(migration.query, /amount DOUBLE PRECISION/);

  const interval = prepareSql("SELECT created_at > datetime('now', '-1 minute') FROM users");
  assert.equal(interval.query, "SELECT created_at > (CURRENT_TIMESTAMP - INTERVAL '1 minutes')::text FROM users");

  const year = prepareSql("SELECT strftime('%Y','now')");
  assert.equal(year.query, "SELECT to_char(CURRENT_TIMESTAMP, 'YYYY')");
});

test('PostgreSQL database adapter passes single positional and named arguments correctly', () => {
  const database = Object.create(PostgresDatabase.prototype);
  const operations = [];
  database.request = (operation) => {
    operations.push(operation);
    return { rows: [{ id: 21 }], rowCount: 1 };
  };

  database.prepare('SELECT * FROM users WHERE id=?').get('user-1');
  database.prepare('SELECT * FROM users WHERE id=@id').get({ id: 'user-2' });
  const insertResult = database.prepare('INSERT INTO call_signals (call_id) VALUES (?)').run('call-1');
  assert.deepEqual(operations.map((operation) => operation.values), [['user-1'], ['user-2'], ['call-1']]);
  assert.equal(operations[2].sql, 'INSERT INTO call_signals (call_id) VALUES ($1) RETURNING id');
  assert.deepEqual(insertResult, { changes: 1, lastInsertRowid: 21 });
});

test('PostgreSQL database selection rejects a non-PostgreSQL DATABASE_URL instead of falling back to SQLite', () => {
  const previousDatabaseUrl = process.env.DATABASE_URL;
  try {
    process.env.DATABASE_URL = 'sqlite://not-a-postgres-database';
    const { createDatabase } = require('../src/db');
    assert.throws(() => createDatabase(), /DATABASE_URL must use the postgres:\/\//);
  } finally {
    if (previousDatabaseUrl === undefined) delete process.env.DATABASE_URL;
    else process.env.DATABASE_URL = previousDatabaseUrl;
  }
});
