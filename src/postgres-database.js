const path = require('node:path');
const { Worker } = require('node:worker_threads');

const BRIDGE_BYTES = 32 * 1024 * 1024;
const encoder = new TextEncoder();
const decoder = new TextDecoder();

const normalizeParams = (params) => params.length === 1
  && params[0] !== null
  && typeof params[0] === 'object'
  && !Array.isArray(params[0])
  && !Buffer.isBuffer(params[0])
  ? params[0]
  : params;

const prepareSql = (sql, params) => {
  const values = Array.isArray(params) ? params : [];
  const namedValues = params && !Array.isArray(params) && typeof params === 'object' ? params : null;
  const ignoreInsert = /\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(sql);
  const placeholders = new Map();
  let nextIndex = 0;
  let quote = null;
  let translated = '';

  for (let index = 0; index < sql.length; index += 1) {
    const character = sql[index];
    if (quote) {
      translated += character;
      if (character === quote) {
        if (sql[index + 1] === quote) translated += sql[++index];
        else quote = null;
      } else if (character === '\\' && quote === "'" && index + 1 < sql.length) {
        translated += sql[++index];
      }
      continue;
    }
    if (character === "'" || character === '"') {
      quote = character;
      translated += character;
      continue;
    }
    if (character === '?' && !namedValues) {
      translated += `$${++nextIndex}`;
      continue;
    }
    if (character === '@' && namedValues && /[A-Za-z_]/.test(sql[index + 1] || '')) {
      let end = index + 2;
      while (/[A-Za-z0-9_]/.test(sql[end] || '')) end += 1;
      const name = sql.slice(index + 1, end);
      if (!placeholders.has(name)) placeholders.set(name, ++nextIndex);
      translated += `$${placeholders.get(name)}`;
      index = end - 1;
      continue;
    }
    translated += character;
  }

  const intervalTimestamps = [];
  const currentYear = '__CLARICARE_CURRENT_YEAR__';
  let query = translated
    .replace(/PRAGMA\s+foreign_keys\s*=\s*ON\s*;?/gi, '')
    .replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, 'INSERT INTO')
    .replace(/([A-Za-z_][\w.]*)\s*=\s*(\$\d+)\s+COLLATE\s+NOCASE/gi, 'LOWER($1) = LOWER($2)')
    .replace(/([A-Za-z_][\w.]*)\s+COLLATE\s+NOCASE/gi, 'LOWER($1)')
    .replace(/\bLIKE\b/gi, 'ILIKE')
    .replace(/datetime\(\s*'now'\s*,\s*'-(\d+)\s+minute[s]?'\s*\)/gi, (_match, minutes) => {
      const marker = `__CLARICARE_INTERVAL_TIMESTAMP_${intervalTimestamps.length}__`;
      intervalTimestamps.push(`(CURRENT_TIMESTAMP - INTERVAL '${minutes} minutes')::text`);
      return marker;
    })
    .replace(/datetime\(\s*([A-Za-z_][\w.]*)\s*\)/gi, '$1')
    .replace(/strftime\(\s*'%Y'\s*,\s*'now'\s*\)/gi, currentYear)
    .replace(/\b([A-Za-z_][\w.]*)\.rowid\b/gi, '$1.id')
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bCURRENT_TIMESTAMP\b/gi, 'CURRENT_TIMESTAMP::text');
  intervalTimestamps.forEach((expression, index) => {
    query = query.replaceAll(`__CLARICARE_INTERVAL_TIMESTAMP_${index}__`, expression);
  });
  query = query.replaceAll(currentYear, "to_char(CURRENT_TIMESTAMP, 'YYYY')");

  if (ignoreInsert) {
    query = query.replace(/;\s*$/, '').trimEnd() + ' ON CONFLICT DO NOTHING';
  }
  const returnsSignalId = /^\s*INSERT\s+INTO\s+call_signals\b/i.test(query);
  if (returnsSignalId && !/\bRETURNING\b/i.test(query)) query = query.replace(/;\s*$/, '') + ' RETURNING id';

  const orderedNames = [...placeholders.keys()].sort((a, b) => placeholders.get(a) - placeholders.get(b));
  for (const name of orderedNames) {
    if (!Object.hasOwn(namedValues, name)) throw new Error(`Missing SQL parameter: ${name}`);
  }
  return {
    query,
    values: namedValues ? orderedNames.map((name) => namedValues[name]) : values,
    returnsSignalId,
  };
};

class PostgresDatabase {
  constructor(connectionString) {
    let parsedUrl;
    try {
      parsedUrl = new URL(connectionString);
    } catch {
      throw new Error('DATABASE_URL must be a valid PostgreSQL connection URL.');
    }
    if (!['postgres:', 'postgresql:'].includes(parsedUrl.protocol)) {
      throw new Error('DATABASE_URL must use the postgres:// or postgresql:// scheme.');
    }
    this.sharedBuffer = new SharedArrayBuffer(BRIDGE_BYTES + 8);
    this.header = new Int32Array(this.sharedBuffer, 0, 2);
    this.body = new Uint8Array(this.sharedBuffer, 8);
    this.worker = new Worker(path.join(__dirname, 'postgres-worker.js'), {
      workerData: { connectionString, sharedBuffer: this.sharedBuffer },
    });
    this.worker.unref();
    this.isPostgres = true;
    this.closed = false;

    const state = Atomics.wait(this.header, 0, 0, 30000);
    if (state === 'timed-out' || Atomics.load(this.header, 0) !== 2) {
      this.worker.terminate();
      throw new Error('Timed out while connecting to the PostgreSQL database.');
    }
    const response = this.readResponse();
    Atomics.store(this.header, 0, 0);
    if (!response.ready) {
      this.worker.terminate();
      const error = new Error(`Could not connect to PostgreSQL: ${response.error?.message || 'Connection failed'}`);
      error.code = response.error?.code;
      throw error;
    }
  }

  readResponse() {
    const length = Atomics.load(this.header, 1);
    return JSON.parse(decoder.decode(this.body.subarray(0, length)));
  }

  request(operation) {
    if (this.closed) throw new Error('The PostgreSQL database connection is closed.');
    const bytes = encoder.encode(JSON.stringify(operation));
    if (bytes.length > this.body.length) throw new Error('PostgreSQL request exceeds the database bridge size limit.');
    this.body.set(bytes);
    Atomics.store(this.header, 1, bytes.length);
    Atomics.store(this.header, 0, 1);
    Atomics.notify(this.header, 0);
    const state = Atomics.wait(this.header, 0, 1, 30000);
    if (state === 'timed-out' || Atomics.load(this.header, 0) !== 2) {
      throw new Error('Timed out while waiting for the PostgreSQL database.');
    }
    const response = this.readResponse();
    Atomics.store(this.header, 0, 0);
    if (response.error) {
      const error = new Error(response.error.message);
      error.code = response.error.code;
      error.detail = response.error.detail;
      throw error;
    }
    return response.result;
  }

  exec(sql) {
    const { query } = prepareSql(sql, []);
    if (!query.trim()) return;
    return this.request({ type: 'query', sql: query, values: [] });
  }

  prepare(sql) {
    const pragmaTable = /^\s*PRAGMA\s+table_info\((\w+)\)\s*;?\s*$/i.exec(sql);
    if (pragmaTable) {
      const table = pragmaTable[1];
      return {
        all: () => this.request({
          type: 'query',
          sql: 'SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=$1 ORDER BY ordinal_position',
          values: [table],
        }).rows,
        get: () => undefined,
        run: () => ({ changes: 0, lastInsertRowid: 0 }),
      };
    }

    return {
      all: (...params) => {
        const prepared = prepareSql(sql, normalizeParams(params));
        return this.request({ type: 'query', sql: prepared.query, values: prepared.values }).rows;
      },
      get: (...params) => {
        const prepared = prepareSql(sql, normalizeParams(params));
        return this.request({ type: 'query', sql: prepared.query, values: prepared.values }).rows[0];
      },
      run: (...params) => {
        const prepared = prepareSql(sql, normalizeParams(params));
        const result = this.request({ type: 'query', sql: prepared.query, values: prepared.values });
        return {
          changes: result.rowCount,
          lastInsertRowid: prepared.returnsSignalId ? result.rows[0]?.id || 0 : 0,
        };
      },
    };
  }

  transaction(callback) {
    return (...args) => {
      this.request({ type: 'begin' });
      try {
        const result = callback(...args);
        if (result && typeof result.then === 'function') {
          throw new Error('PostgreSQL compatibility transactions require a synchronous callback.');
        }
        this.request({ type: 'commit' });
        return result;
      } catch (error) {
        this.request({ type: 'rollback' });
        throw error;
      }
    };
  }

  close() {
    if (this.closed) return;
    try {
      this.request({ type: 'close' });
    } finally {
      this.closed = true;
      this.worker.terminate();
    }
  }
}

module.exports = { PostgresDatabase, prepareSql };
